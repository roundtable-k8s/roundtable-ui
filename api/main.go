func knightSessionHandler(fleetPrefix string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		vars := mux.Vars(r)
		name := vars["knight"]
		reqType := r.URL.Query().Get("type")
		if reqType == "" {
			reqType = "stats"
		}
		if !validSessionTypes[reqType] {
			jsonError(w, "Invalid session type (allowed: stats, recent, tree, history, session)", http.StatusBadRequest)
			return
		}

		// type=session requires a valid id (which JSONL file to read). Validate up
		// front so a bad id fails fast regardless of knight readiness.
		sessionID := r.URL.Query().Get("id")
		if reqType == "session" && !validSessionID.MatchString(sessionID) {
			jsonError(w, "Invalid or missing session id", http.StatusBadRequest)
			return
		}

		// Validate knight name (prevents NATS subject injection)
		if !validKnightName.MatchString(name) {
			jsonError(w, "Invalid knight name", http.StatusBadRequest)
			return
		}

		// pod selects one pod's per-pod subject; runId selects the run's
		// session on that pod (#219). Both end up in NATS subjects/payloads.
		podParam := r.URL.Query().Get("pod")
		if podParam != "" && !validPodName(podParam) {
			jsonError(w, "Invalid pod name", http.StatusBadRequest)
			return
		}
		runID := r.URL.Query().Get("runId")
		if runID != "" && !validRunID.MatchString(runID) {
			jsonError(w, "Invalid runId", http.StatusBadRequest)
			return
		}

		// Fetch the Knight CR once — it supplies both the readiness signal and
		// the NATS prefix, so non-fleet-a knights (e.g. chelonian, rt-dev) are
		// queried on their own table's subject instead of the hardcoded
		// FLEET_PREFIX.
		ctx := r.Context()
		prefix := fleetPrefix // graceful degradation when the CR is unavailable
		if knightCR, err := getKnightCR(ctx, name); err != nil {
			slog.WarnContext(ctx, "Failed to fetch Knight CR, falling back to FLEET_PREFIX", "knight", name, "error", err)
		} else {
			// Short-circuit offline knights: proxying introspect to a knight
			// whose pod is not ready just blocks until the NATS request timeout
			// and surfaces as a 504 on the dashboard. Return the frontend's
			// "no data" shape ({}) immediately instead — every caller guards on
			// .session / .runtime / .entries / .nodes being present.
			if !knightIsReady(knightCR) {
				slog.DebugContext(ctx, "Knight not ready, skipping introspect", "knight", name)
				// Scaled to zero: a named pod is certainly gone (#220).
				if podParam != "" && looksLikeKnightPod(name, podParam) {
					writePodGone(w, podParam)
					return
				}
				w.Header().Set("Content-Type", "application/json")
				w.Write([]byte("{}"))
				return
			}
			if p, perr := deriveIntrospectPrefix(knightCR); perr == nil {
				prefix = p
			} else {
				slog.WarnContext(ctx, "Failed to derive introspect prefix, falling back to FLEET_PREFIX", "knight", name, "error", perr)
			}
		}

		req := sessionRequester()
		if req == nil {
			jsonError(w, "NATS not available", http.StatusServiceUnavailable)
			return
		}

		// Forward a validated entry limit (pi-knight defaults to 20 for type=recent)
		introspectReq := map[string]interface{}{"type": reqType}
		if limStr := r.URL.Query().Get("limit"); limStr != "" {
			if lim, limErr := strconv.Atoi(limStr); limErr == nil && lim > 0 && lim <= 500 {
				introspectReq["limit"] = lim
			}
		}
		// type=session takes the (already-validated) id and an optional page offset.
		if reqType == "session" {
			introspectReq["id"] = sessionID
			if offStr := r.URL.Query().Get("offset"); offStr != "" {
				if off, offErr := strconv.Atoi(offStr); offErr == nil && off >= 0 {
					introspectReq["offset"] = off
				}
			}
		}
		if runID != "" {
			introspectReq["runId"] = runID
		}
		payload, _ := json.Marshal(introspectReq)

		// history/session read JSONL off the knight's PVC — give them more headroom
		// than the in-memory stats/recent/tree queries.
		timeout := 5 * time.Second
		if reqType == "history" || reqType == "session" {
			timeout = 12 * time.Second
		}

		serveIntrospect(w, ctx, req, prefix, name, podParam, reqType, payload, timeout)
	}
}

// serveIntrospect routes one introspect request to the right pod(s); see
// introspect.go for the per-pod model.
func serveIntrospect(w http.ResponseWriter, ctx context.Context, req introspectRequester, prefix, name, podParam, reqType string, payload []byte, timeout time.Duration) {
	namespace := envOr("NAMESPACE", "roundtable")
	pods, podErr := knightPodsForIntrospect(ctx, namespace, name)
	if podErr != nil {
		slog.WarnContext(ctx, "Introspect: pod list failed", "knight", name, "error", podErr)
	}

	knightLevel := func(scope string) {
		subject := knightIntrospectSubject(prefix, name)
		data, err := req(subject, payload, timeout)
		if err != nil {
			slog.WarnContext(ctx, "Knight introspect timeout", "knight", name, "subject", subject, "error", err)
			jsonError(w, "Knight introspection timeout", http.StatusGatewayTimeout)
			return
		}
		w.Header().Set(introspectScopeHeader, scope)
		writeRedactedJSON(w, data)
	}

	// Explicit pod: only that pod may answer.
	if podParam != "" {
		if podErr != nil {
			jsonError(w, "Cannot verify pod: pod list unavailable", http.StatusServiceUnavailable)
			return
		}
		known := false
		for _, p := range pods {
			if p == podParam {
				known = true
				break
			}
		}
		if !known {
			// A name shaped like this knight's pods that is no longer
			// Running+Ready was scaled away (or crashed): say so at once
			// instead of letting the dashboard wait for a NATS timeout (#220).
			if looksLikeKnightPod(name, podParam) {
				writePodGone(w, podParam)
				return
			}
			jsonError(w, "Unknown pod for this knight", http.StatusNotFound)
			return
		}
		subject := podIntrospectSubject(prefix, name, podParam)
		data, err := req(subject, payload, timeout)
		if err != nil {
			// An older runtime only listens on the knight subject; that is
			// still this pod when it is the knight's only one.
			if isNoResponders(err) && len(pods) == 1 {
				knightLevel("pod")
				return
			}
			if isNoResponders(err) {
				jsonError(w, "Pod does not support per-pod introspection", http.StatusBadGateway)
				return
			}
			slog.WarnContext(ctx, "Knight introspect timeout", "knight", name, "subject", subject, "error", err)
			jsonError(w, "Knight introspection timeout", http.StatusGatewayTimeout)
			return
		}
		w.Header().Set(introspectScopeHeader, "pod")
		writeRedactedJSON(w, withPod(data, podParam))
		return
	}

	// No pod list (no Kubernetes access): keep the legacy knight-level path.
	if podErr != nil || len(pods) == 0 {
		knightLevel("knight")
		return
	}

	replies := fanOutIntrospect(req, prefix, name, pods, payload, timeout)
	if allNoResponders(replies) {
		knightLevel("knight") // older runtime without per-pod subjects
		return
	}

	var out []byte
	switch reqType {
	case "stats", "history":
		var agg map[string]interface{}
		var ok bool
		if reqType == "stats" {
			agg, ok = aggregateStats(name, replies)
		} else {
			agg, ok = mergeHistory(replies)
		}
		if !ok {
			jsonError(w, "Knight introspection timeout", http.StatusGatewayTimeout)
			return
		}
		out, _ = json.Marshal(agg)
	default: // session, recent, tree: the pod that has the data answers
		pick, ok := pickFirstFound(replies)
		if !ok {
			jsonError(w, "Knight introspection timeout", http.StatusGatewayTimeout)
			return
		}
		out = withPod(pick.Data, pick.Pod)
	}
	w.Header().Set(introspectScopeHeader, "aggregate")
	writeRedactedJSON(w, out)
}

// taskHistoryHandler returns recent results from every table's results
// stream (#239), oldest first, each tagged with its table. ?table=<name>
// narrows to one table. The covered tables are returned too so the UI can
// offer a filter even before any task ran.
func taskHistoryHandler(src *tableSource) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		ctx := r.Context()
		tables := src.tables(ctx)
		selected := tables
		if name := r.URL.Query().Get("table"); name != "" {
			t, ok := findTableByName(tables, name)
			if !ok {
				jsonError(w, "Unknown table", http.StatusBadRequest)
				return
			}
			selected = []TableInfo{t}
		}

		results := []TaskEvent{}
		var total uint64
		unavailable := []string{}
		for _, t := range selected {
			if t.ResultsStream == "" {
				unavailable = append(unavailable, t.Name)
				continue
			}
			events, msgs, err := readResults(ctx, t.ResultsStream, t.Prefix+".results.>", taskHistoryPerTable)
			if err != nil {
				slog.ErrorContext(ctx, "JetStream task history error", "table", t.Name, "stream", t.ResultsStream, "error", err)
				unavailable = append(unavailable, t.Name)
				continue
			}
			total += msgs
			for _, e := range events {
				e.Table = t.Name
				results = append(results, e)
			}
		}
		if len(unavailable) == len(selected) {
			jsonError(w, "Task history unavailable", http.StatusInternalServerError)
			return
		}

		sort.SliceStable(results, func(i, j int) bool { return results[i].Timestamp.Before(results[j].Timestamp) })
		if len(results) > taskHistoryMax {
			results = results[len(results)-taskHistoryMax:]
		}

		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(map[string]interface{}{
			"results":     results,
			"messages":    total,
			"tables":      tables,
			"unavailable": unavailable,
		})
	}
}

const (
	taskHistoryPerTable = 50  // newest results read per table
	taskHistoryMax      = 200 // cap on the merged list (the UI keeps 200 events)
)

// defaultBriefingDirs are the vault-relative directories searched for
// briefings when BRIEFINGS_DIRS is unset.
const defaultBriefingDirs = "Briefings/Daily,Agents/Briefings"

// parseBriefingDirs splits a comma-separated list of vault-relative
// directories, dropping empty, absolute, traversing and duplicate entries.
func parseBriefingDirs(raw string) []string {
	dirs := []string{}
	seen := map[string]bool{}
	for _, d := range strings.Split(raw, ",") {
		d = strings.TrimSpace(d)
		if d == "" || filepath.IsAbs(d) {
			continue
		}
		d = filepath.Clean(d)
		if d == "." || d == ".." || strings.HasPrefix(d, ".."+string(filepath.Separator)) || seen[d] {
			continue
		}
		seen[d] = true
		dirs = append(dirs, d)
	}
	return dirs
}

type briefingEntry struct {
	Name string `json:"name"`
	Dir  string `json:"dir"`
}

// briefingListHandler lists briefings across all configured directories.
// Missing directories are skipped; the result is an empty list, not an error.
func briefingListHandler(vaultPath string, dirs []string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		briefings := []briefingEntry{}
		for _, d := range dirs {
			entries, err := os.ReadDir(filepath.Join(vaultPath, d))
			if err != nil {
				if !os.IsNotExist(err) {
					slog.WarnContext(r.Context(), "cannot read briefings directory", "dir", d, "error", err)
				}
				continue
			}
			for _, e := range entries {
				if !e.IsDir() && strings.HasSuffix(e.Name(), ".md") && briefingDateRe.MatchString(strings.TrimSuffix(e.Name(), ".md")) {
					briefings = append(briefings, briefingEntry{Name: e.Name(), Dir: d})
				}
			}
		}

		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(briefings)
	}
}

var briefingDateRe = regexp.MustCompile(`^\d{4}-\d{2}-\d{2}$`)

// maxBriefingBytes caps how much of one briefing the API reads and returns.
const maxBriefingBytes = 2 << 20

var briefingTooLargeMsg = fmt.Sprintf("Briefing too large (limit %d bytes)", maxBriefingBytes)

// briefingHandler serves one briefing. The optional ?dir= query selects one of
// the configured directories; otherwise they are searched in order.
func briefingHandler(vaultPath string, dirs []string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		date := mux.Vars(r)["date"]

		// Sanitize: only allow YYYY-MM-DD format to prevent path traversal
		if !briefingDateRe.MatchString(date) {
			jsonError(w, "Invalid date format", http.StatusBadRequest)
			return
		}

		search := dirs
		if want := r.URL.Query().Get("dir"); want != "" {
			// Only configured directories are allowed.
			search = nil
			for _, d := range dirs {
				if d == filepath.Clean(want) {
					search = []string{d}
					break
				}
			}
			if search == nil {
				jsonError(w, "Forbidden", http.StatusForbidden)
				return
			}
		}

		for _, d := range search {
			p := filepath.Join(vaultPath, d, date+".md")
			// Stat before Open: opening a FIFO blocks until a writer appears, so
			// only regular files (after following symlinks) are opened.
			if fi, err := os.Stat(p); err == nil && !fi.Mode().IsRegular() {
				continue
			}
			f, err := os.Open(p)
			if err != nil {
				if errors.Is(err, fs.ErrNotExist) {
					continue
				}
				slog.ErrorContext(r.Context(), "briefing read failed", "dir", d, "error", err)
				jsonError(w, "Failed to read briefing", http.StatusInternalServerError)
				return
			}
			info, err := f.Stat()
			if err != nil {
				f.Close()
				slog.ErrorContext(r.Context(), "briefing read failed", "dir", d, "error", err)
				jsonError(w, "Failed to read briefing", http.StatusInternalServerError)
				return
			}
			if info.IsDir() {
				f.Close()
				continue
			}
			if info.Size() > maxBriefingBytes {
				f.Close()
				jsonError(w, briefingTooLargeMsg, http.StatusRequestEntityTooLarge)
				return
			}
			// Read one byte past the cap so a file that grew after Stat is still caught.
			content, err := io.ReadAll(io.LimitReader(f, maxBriefingBytes+1))
			f.Close()
			if err != nil {
				slog.ErrorContext(r.Context(), "briefing read failed", "dir", d, "error", err)
				jsonError(w, "Failed to read briefing", http.StatusInternalServerError)
				return
			}
			if len(content) > maxBriefingBytes {
				jsonError(w, briefingTooLargeMsg, http.StatusRequestEntityTooLarge)
				return
			}
			w.Header().Set("Content-Type", "text/markdown")
			w.Header().Set("X-Briefing-Dir", d)
			w.Write(content)
			return
		}
		jsonError(w, "Briefing not found", http.StatusNotFound)
	}
}

func wsHandler(src *tableSource, running *runningRegistry, activity *activityStore, chains *chainWatcher, cards *cardStore, tc *tableCache) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		// Check NATS health BEFORE upgrading (#19). Upgrading first and then
		// closing makes the client fire onopen (UI shows "Connected") before
		// the close arrives, so the indicator flickers connected/disconnected
		// on every reconnect. Rejecting the upgrade with 503 keeps the client
		// cleanly "Disconnected" while the backend is degraded.
		if !nc.IsConnected() {
			slog.WarnContext(r.Context(), "NATS not connected, rejecting WS")
			jsonError(w, "NATS unavailable", http.StatusServiceUnavailable)
			return
		}

		life := wsLife
		if !life.enter() {
			jsonError(w, "server shutting down", http.StatusServiceUnavailable)
			return
		}
		defer life.leave()

		// Connection cap (#378), enforced before the upgrade so a rejected
		// client costs no subscriptions or goroutines.
		if !wsAcquire() {
			wsRejectedTotal.Inc()
			slog.WarnContext(r.Context(), "too many WebSocket connections, rejecting", "max", wsMaxConnections)
			w.Header().Set("Retry-After", "5")
			jsonError(w, "Too many WebSocket connections", http.StatusServiceUnavailable)
			return
		}
		defer wsRelease()

		conn, err := upgrader.Upgrade(w, r, nil)
		if err != nil {
			slog.ErrorContext(r.Context(), "WebSocket upgrade error", "error", err)
			return
		}
		// Clients only send small activity commands; an oversize frame ends
		// the connection with websocket.ErrReadLimit (#378).
		conn.SetReadLimit(wsMaxClientMessageBytes)

		// Serialized writer — gorilla websocket is not concurrent-write safe (#42, #96)
		// Bounded outbound queue drained by one writer goroutine; NATS
		// callbacks only enqueue, so a slow client cannot block them or grow
		// memory without bound (#97). See the wsWriter docs for the policy.
		ws := newWSWriter(conn, wsQueueSize, func() { conn.Close() })
		go ws.run()
		if wsWriterHook != nil {
			wsWriterHook(ws)
		}
		safeWrite := func(critical bool, data []byte) { ws.enqueue(data, critical) }

		// Done channel to clean up NATS subscriptions when WS closes
		done := make(chan struct{})

		// Subscribe to task and result events of every table (#239). Tables
		// are resolved per connection; a table added later shows up on the
		// next (re)connect.
		tables := src.tables(r.Context())
		forward := func(eventType string, critical bool) nats.MsgHandler {
			return func(msg *nats.Msg) {
				select {
				case <-done:
					return
				default:
				}
				event := TaskEvent{
					Type:      eventType,
					Subject:   msg.Subject,
					Data:      msg.Data,
					Timestamp: eventTimestamp(msg.Data),
				}
				if t, ok := tableForSubject(tables, msg.Subject); ok {
					event.Table = t.Name
				}
				data, _ := json.Marshal(event)
				safeWrite(critical, data)
			}
		}
		var subs []*nats.Subscription
		unsubscribeAll := func() {
			for _, sub := range subs {
				sub.Unsubscribe()
			}
		}
		for _, sub := range wsSubscriptions(tables) {
			ns, err := wsSubscribe(sub.subject, forward(sub.eventType, sub.critical))
			if err != nil {
				slog.ErrorContext(r.Context(), "NATS subscribe error", "subject", sub.subject, "error", err)
				unsubscribeAll()
				ws.close() // stop the writer goroutine started above (#378)
				conn.Close()
				return
			}
			subs = append(subs, ns)
		}

		// Chain changes (#228) come from a Kubernetes watch on Chain
		// resources. The operator never published <prefix>.chains.> or
		// <prefix>.missions.> on NATS, so those subscriptions were removed.
		var unsubChains func()
		if chains != nil {
			unsubChains = chains.subscribe(func(data []byte) { safeWrite(true, data) })
		}

		// Agent card changes (#251) from a KV watch on the cards bucket.
		var unsubCards func()
		if cards != nil {
			unsubCards = cards.subscribe(func(data []byte) { safeWrite(true, data) })
		}

		// In-flight registry deltas (#199): a snapshot first, then upserts and
		// removes. Critical: a dropped delta would leave the client's view
		// wrong until it refetches.
		var unsubRunning func()
		if running != nil {
			// Tag tasks with their table like GET /api/running. The lookup
			// happens here and in a background loop, never inside the
			// registry callback (which runs under its lock).
			// The cache is process-wide (shared by every connection).
			unsubRunning = running.subscribe(func(d RunningDelta) {
				tbl := tc.get()
				safeWrite(true, runningWSEvent(withTables(d, tbl)))
			})
		}

		// Task activity (#184): only the tasks this client subscribed to.
		var activityWatches *activityClient
		if activity != nil {
			activityWatches = newActivityClient(activity, ws.enqueue)
		}

		// Cleanup on exit
		defer func() {
			if activityWatches != nil {
				activityWatches.close()
			}
			if unsubRunning != nil {
				unsubRunning()
			}
			if unsubChains != nil {
				unsubChains()
			}
			if unsubCards != nil {
				unsubCards()
			}
			close(done)
			unsubscribeAll()
			ws.close()
			conn.Close()
		}()

		// Keep connection alive, read client messages (activity watches)
		conn.SetReadDeadline(time.Now().Add(60 * time.Second))
		conn.SetPongHandler(func(string) error {
			conn.SetReadDeadline(time.Now().Add(60 * time.Second))
			return nil
		})

		// Clean 1001 close on server shutdown; clients reconnect with back-off.
		go func() {
			select {
			case <-done:
			case <-life.shutdown:
				closeGoingAway(ws, conn)
			}
		}()

		// Ping ticker to detect dead connections
		ticker := time.NewTicker(30 * time.Second)
		defer ticker.Stop()
		go func() {
			for {
				select {
				case <-done:
					return
				case <-ticker.C:
					if ws.isClosed() || !ws.write(websocket.PingMessage, nil) {
						return
					}
				}
			}
		}()

		for {
			_, msg, err := conn.ReadMessage()
			if err != nil {
				break
			}
			conn.SetReadDeadline(time.Now().Add(60 * time.Second))

			if activityWatches != nil && activityWatches.handle(msg) {
				continue
			}

		}
	}
}

// wsSubscription is one NATS subscription a WS client gets.
type wsSubscription struct {
	subject   string
	eventType string // task | result
	critical  bool   // results must not be dropped under backpressure
}

// wsSubscriptions lists the task and result subscriptions for the tables,
// one pair per distinct prefix.
func wsSubscriptions(tables []TableInfo) []wsSubscription {
	var out []wsSubscription
	seen := map[string]bool{}
	for _, t := range tables {
		if seen[t.Prefix] {
			continue
		}
		seen[t.Prefix] = true
		out = append(out,
			wsSubscription{subject: t.Prefix + ".tasks.>", eventType: "task"},
			wsSubscription{subject: t.Prefix + ".results.>", eventType: "result", critical: true},
		)
	}
	return out
}

