// knightIsReady reports whether the operator marked the Knight as ready to
// accept tasks (status.ready, mirrored by status.phase=Ready). The operator
// derives this from deployment/pod readiness, so it doubles as a cheap
// reachability signal for introspect requests.
func knightIsReady(obj *unstructured.Unstructured) bool {
	status := getNestedMap(obj.Object, "status")
	return getBool(status, "ready") || getStr(status, "phase") == "Ready"
}

// deriveIntrospectPrefix extracts the NATS prefix for introspection from a Knight CR.
// This allows the dashboard to support multiple tables (fleet-a, chelonian, etc.) without hardcoding.
func deriveIntrospectPrefix(obj *unstructured.Unstructured) (string, error) {
	knightName := obj.GetName()

	// Extract .spec.nats.subjects[]
	subjects, found, err := unstructured.NestedStringSlice(obj.Object, "spec", "nats", "subjects")
	if err != nil || !found || len(subjects) == 0 {
		return "", fmt.Errorf("knight %s has no nats.subjects configured", knightName)
	}

	// Derive prefix using same logic as operator (internal/knight/pod_builder.go DeriveResultsPrefix)
	for _, subj := range subjects {
		if strings.Contains(subj, ".tasks.") {
			parts := strings.SplitN(subj, ".tasks.", 2)
			if len(parts) == 2 {
				return parts[0], nil
			}
		}
	}

	// Fallback: use first segment
	for _, subj := range subjects {
		parts := strings.Split(subj, ".")
		if len(parts) > 1 {
			return parts[0], nil
		}
	}

	return "", fmt.Errorf("could not derive NATS prefix from knight %s subjects", knightName)
}

// validTraceID is a W3C trace ID: 32 hex characters.
var validTraceID = regexp.MustCompile(`^[0-9a-fA-F]{32}$`)

// traceTemplate returns the trace viewer URL template when it is an http(s)
// URL containing {traceId}; otherwise "" (with a warning when it was set).
func traceTemplate(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return ""
	}
	u, err := url.Parse(raw)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" || !strings.Contains(raw, "{traceId}") {
		slog.Warn("TRACE_URL_TEMPLATE ignored: need an http(s) URL containing {traceId}")
		return ""
	}
	return raw
}

