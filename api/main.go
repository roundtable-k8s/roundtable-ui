func missionCreateHandler(namespace string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if dynClient == nil {
			jsonError(w, "Kubernetes not available", http.StatusServiceUnavailable)
			return
		}

		// Parse request body
		var reqBody map[string]interface{}
		if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<20)).Decode(&reqBody); err != nil {
			jsonError(w, "Invalid request body", http.StatusBadRequest)
			return
		}

		// Validate required fields
		name, ok := reqBody["name"].(string)
		if !ok || !validK8sName.MatchString(name) {
			jsonError(w, "Invalid mission name", http.StatusBadRequest)
			return
		}

		// Validate objective
		objective, _ := reqBody["objective"].(string)
		if n := utf8.RuneCountInString(objective); strings.TrimSpace(objective) == "" || n > 1000 {
			jsonError(w, "Objective required (1-1000 chars)", http.StatusBadRequest)
			return
		}

		// Validate TTL if provided (60-604800 seconds)
		if ttl, ok := reqBody["ttlSeconds"].(float64); ok {
			if ttl < 60 || ttl > 604800 {
				jsonError(w, "TTL must be 60-604800 seconds", http.StatusBadRequest)
				return
			}
		}

		// Validate timeout if provided (60-86400 seconds)
		if timeout, ok := reqBody["timeoutSeconds"].(float64); ok {
			if timeout < 60 || timeout > 86400 {
				jsonError(w, "Timeout must be 60-86400 seconds", http.StatusBadRequest)
				return
			}
		}

		// Validate cleanupPolicy if provided
		if policy, ok := reqBody["cleanupPolicy"].(string); ok {
			if policy != "Delete" && policy != "Retain" {
				jsonError(w, "cleanupPolicy must be Delete or Retain", http.StatusBadRequest)
				return
			}
		}

		// planner.knightRef is optional for meta-missions: when omitted the
		// operator uses the planner of the mission's RoundTable. If one is
		// given, its name must still be valid.
		if meta, _ := reqBody["metaMission"].(bool); meta {
			if planner, _ := reqBody["planner"].(map[string]interface{}); planner != nil {
				if ref, present := planner["knightRef"]; present && ref != nil {
					if !validK8sName.MatchString(getRefName(planner, "knightRef")) {
						jsonError(w, "planner.knightRef.name must be a valid knight name", http.StatusBadRequest)
						return
					}
				}
			}
		}

		// Build mission object — copy the request body into spec without the
		// metadata-level name key (it is not a spec field)
		spec := make(map[string]interface{}, len(reqBody))
		for k, v := range reqBody {
			if k != "name" {
				spec[k] = v
			}
		}
		mission := map[string]interface{}{
			"apiVersion": "ai.roundtable.io/v1alpha1",
			"kind":       "Mission",
			"metadata": map[string]interface{}{
				"name":      name,
				"namespace": namespace,
			},
			"spec": spec,
		}

		// Create via dynamic client
		obj, err := dynClient.Resource(missionGVR).Namespace(namespace).Create(
			r.Context(),
			&unstructured.Unstructured{Object: mission},
			metav1.CreateOptions{},
		)
		if err != nil {
			code, msg := k8sErrorStatus(r.Context(), err, "create")
			jsonError(w, msg, code)
			return
		}

		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusCreated)
		json.NewEncoder(w).Encode(map[string]interface{}{
			"name":      obj.GetName(),
			"namespace": obj.GetNamespace(),
			"created":   true,
			"uid":       obj.GetUID(),
		})
	}
}

