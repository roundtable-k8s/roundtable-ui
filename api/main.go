func parseMissionResource(obj map[string]interface{}) MissionSummary {
	spec := getNestedMap(obj, "spec")
	status := getNestedMap(obj, "status")
	metadata := getNestedMap(obj, "metadata")

	mission := MissionSummary{
		Name:             getStr(metadata, "name"),
		Namespace:        getStr(metadata, "namespace"),
		Phase:            getStr(status, "phase"),
		Objective:        getStr(spec, "objective"),
		CostBudgetUSD:    getStr(spec, "costBudgetUSD"),
		TotalCost:        getStr(status, "totalCost"),
		TTLSeconds:       getInt(spec, "ttlSeconds"),
		TimeoutSeconds:   getInt(spec, "timeoutSeconds"),
		RoundTableRef:    getRefName(spec, "roundTableRef"),
		Table:            tableOrNone(getRefName(spec, "roundTableRef")),
		MetaMission:      getBool(spec, "metaMission"),
		SuccessCriteria:  getStr(spec, "successCriteria"),
		Briefing:         getStr(spec, "briefing"),
		CleanupPolicy:    getStr(spec, "cleanupPolicy"),
		RecruitExisting:  getBool(spec, "recruitExisting"),
		RetainResults:    getBool(spec, "retainResults"),
		ResultsConfigMap: getStr(status, "resultsConfigMap"),
	}

	// Parse timing
	if t := getStr(status, "startedAt"); t != "" {
		mission.StartedAt = &t
	}
	if t := getStr(status, "expiresAt"); t != "" {
		mission.ExpiresAt = &t
	}

	// Parse knights array
	if knights := getSlice(spec, "knights"); knights != nil {
		for _, k := range knights {
			if km, ok := k.(map[string]interface{}); ok {
				if name := getStr(km, "name"); name != "" {
					mission.Knights = append(mission.Knights, name)
				}
			}
		}
	}

	// Parse chains array
	if chains := getSlice(spec, "chains"); chains != nil {
		for _, c := range chains {
			if cm, ok := c.(map[string]interface{}); ok {
				if name := getStr(cm, "name"); name != "" {
					mission.Chains = append(mission.Chains, name)
				}
			}
		}
	}

	// Parse knightStatuses from status
	if ks := getSlice(status, "knightStatuses"); ks != nil {
		for _, k := range ks {
			if km, ok := k.(map[string]interface{}); ok {
				dto := MissionKnightStatusDTO{
					Name:      getStr(km, "name"),
					Ready:     getBool(km, "ready"),
					Ephemeral: getBool(km, "ephemeral"),
				}
				if v, ok := km["tasksCompleted"]; ok {
					switch n := v.(type) {
					case float64:
						dto.TasksCompleted = int64(n)
					case int64:
						dto.TasksCompleted = n
					}
				}
				mission.KnightStatuses = append(mission.KnightStatuses, dto)
			}
		}
	}

	// Parse chainStatuses from status
	if cs := getSlice(status, "chainStatuses"); cs != nil {
		for _, c := range cs {
			if cm, ok := c.(map[string]interface{}); ok {
				dto := MissionChainStatusDTO{
					Name:        getStr(cm, "name"),
					ChainCRName: getStr(cm, "chainCRName"),
					Phase:       getStr(cm, "phase"),
					Tokens:      getTokens(cm, "tokens"),
				}
				if _, ok := parseCost(getStr(cm, "costUSD")); ok {
					dto.CostUSD = getStr(cm, "costUSD")
				}
				mission.ChainStatuses = append(mission.ChainStatuses, dto)
			}
		}
	}

	// Parse completedAt from status
	if t := getStr(status, "completedAt"); t != "" {
		mission.CompletedAt = &t
	}
	mission.Tokens = getTokens(status, "tokens")
	mission.TraceID = statusTraceID(status)

	// Parse planning result
	if pr := getNestedMap(status, "planningResult"); pr != nil {
		mission.PlanningResult = &PlanningResult{
			CompletedAt:      getStr(pr, "completedAt"),
			ChainsGenerated:  getInt(pr, "chainsGenerated"),
			KnightsGenerated: getInt(pr, "knightsGenerated"),
			SkillsGenerated:  getInt(pr, "skillsGenerated"),
			Error:            getStr(pr, "error"),
			RawOutput:        getStr(pr, "rawOutput"),
		}
	}

	return mission
}

