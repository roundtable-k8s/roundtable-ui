	vaultPath := envOr("VAULT_PATH", "/vault")
	briefingDirs := parseBriefingDirs(envOr("BRIEFINGS_DIRS", defaultBriefingDirs))

	// Connect to NATS. Reconnect forever: NATS can restart underneath a
	// long-lived dashboard pod, and the nats.go defaults (MaxReconnects=60)
	// give up after ~2min and permanently close the connection — every WS
	// then flaps "connected/disconnected" and introspect calls fail with
	// "nats: connection closed" until the pod is manually restarted.
	var err error
	nc, err = nats.Connect(natsURL,
		nats.MaxReconnects(-1), // never give up
		nats.ReconnectWait(2*time.Second),
		nats.ReconnectJitter(500*time.Millisecond, 2*time.Second),
		nats.RetryOnFailedConnect(true), // don't hard-exit if NATS is briefly down at boot
		nats.DisconnectErrHandler(func(_ *nats.Conn, err error) {
			slog.Warn("NATS disconnected, will retry", "error", err)
		}),
		nats.ReconnectHandler(func(c *nats.Conn) {
			slog.Info("NATS reconnected", "url", c.ConnectedUrl())
		}),
		nats.ClosedHandler(func(_ *nats.Conn) {
			slog.Error("NATS connection permanently closed")
		}),
	)
	if err != nil {
		slog.Error("NATS connect failed", "error", err, "url", natsURL)
		os.Exit(1)
	}
	defer nc.Close()

	js, err = jetstream.New(nc)
	if err != nil {
		slog.Error("JetStream init failed", "error", err)
		os.Exit(1)
	}
	queues = jsQueueBackend{js: js}
	slog.Info("NATS connected", "url", natsURL)

	// Connect to Kubernetes (in-cluster, falling back to kubeconfig for local dev)
	config, err := rest.InClusterConfig()
	if err != nil {
		slog.Warn("K8s in-cluster config failed (running outside cluster?)", "error", err)
		if cfg, kerr := clientcmd.NewNonInteractiveDeferredLoadingClientConfig(
			clientcmd.NewDefaultClientConfigLoadingRules(),
			&clientcmd.ConfigOverrides{},
		).ClientConfig(); kerr != nil {
			slog.Warn("Kubeconfig fallback failed", "error", kerr)
		} else {
			config = cfg
			err = nil
			slog.Info("Using kubeconfig (local dev)")
		}
	}
	if err == nil {
		// Assign globals only on success — a typed-nil client would defeat the
		// k8sClient != nil availability checks in handlers
		if cs, csErr := kubernetes.NewForConfig(config); csErr != nil {
			slog.Warn("K8s client creation failed", "error", csErr)
		} else {
			k8sClient = cs
			slog.Info("Kubernetes client connected")
		}
		if dc, dcErr := dynamic.NewForConfig(config); dcErr != nil {
			slog.Warn("Dynamic K8s client creation failed", "error", dcErr)
		} else {
			dynClient = dc
		}
	}

	// In-flight task registry fed by knight activity events (#199)
	runningCtx, stopRunning := context.WithCancel(context.Background())
	defer stopRunning()
	running := newRunningRegistry(defaultRunningMaxEntries, runningHeartbeatInterval())
	activity := newActivityStore()
	// Tables come from RoundTable resources; FLEET_PREFIX/FLEET_STREAM
	// optionally narrow them to one table (#239).
	tables := newTableSourceFromEnv(namespace)
	fleetPrefix := tables.defaultPrefix()
	startRunningRegistry(runningCtx, running, activity, tables.prefixes, namespace)

	// Live chain updates over WS (#228)
	var chains *chainWatcher
	if dynClient != nil {
		chains = newChainWatcher(dynClient, namespace, running)
		go chains.run(runningCtx)
	}

	// Agent cards from NATS KV plus knight STATS, pushed live over WS (#251)
	cards := newCardStore(nc, js, envOr("CARDS_KV_BUCKET", defaultCardsBucket), tables.tables)
	go cards.run(runningCtx)

	// Queue history sampler (#205): 15s samples, 6h in-memory ring buffer
	samplerCtx, stopSampler := context.WithCancel(context.Background())
	defer stopSampler()
	var sampler *queueSampler
	if dynClient != nil {
		sampler = newClusterQueueSampler(namespace)
		go sampler.run(samplerCtx)
	}

	// Simple rate limiter (#12)
	rateLimiter := newRateLimiter(100, time.Second) // 100 req/s

	// Router
