func parseChainResource(obj map[string]interface{}, knights map[string]knightInfo) ChainSummary {
	spec := getNestedMap(obj, "spec")
	status := getNestedMap(obj, "status")
	metadata := getNestedMap(obj, "metadata")

	chain := ChainSummary{
		Name:      getStr(metadata, "name"),
		Namespace: getStr(metadata, "namespace"),
		Phase:     getStr(status, "phase"),
	}

	// Schedule from spec (plain cron string in CRD)
	chain.Schedule = getStr(spec, "schedule")
	if chain.Schedule != "" {
		chain.TimeZone = getStr(spec, "timeZone")
		chain.NextScheduledAt = getStr(status, "nextScheduledAt")
		chain.LastScheduledAt = getStr(status, "lastScheduledAt")
	}

	// Spec metadata the Chains page renders (description, refs, suspension…)
	chain.Description = getStr(spec, "description")
	chain.TimeoutSeconds = getInt(spec, "timeoutSeconds")
	chain.OutputKnight = getRefName(spec, "outputKnightRef")
	chain.RoundTableRef = getRefName(spec, "roundTableRef")
	chain.Table = tableOrNone(chain.RoundTableRef)
	chain.MissionRef = getRefName(spec, "missionRef")
	chain.Suspend = getBool(spec, "suspend")
	chain.Invokable = getNestedMap(metadata, "labels")["ai.roundtable.io/invokable"] == "true"
	chain.RunTemplate = chainRunTemplate(metadata)

	// Scheduled-run counters from status
	chain.RunsCompleted = getInt(status, "runsCompleted")
	chain.RunsFailed = getInt(status, "runsFailed")
	chain.RunID = getStr(status, "runId")
	chain.TraceID = statusTraceID(status)

	// Timing (CRD fields: startedAt, completedAt)
	if t := getStr(status, "startedAt"); t != "" {
		chain.StartTime = &t
	}
	if t := getStr(status, "completedAt"); t != "" {
		chain.CompletionTime = &t
	}

	// Current step
	// Derive currentStep from stepStatuses (no CRD field for this)
	for _, s := range getSlice(status, "stepStatuses") {
		if sm, ok := s.(map[string]interface{}); ok {
			if getStr(sm, "phase") == "Running" {
				chain.CurrentStep = getStr(sm, "name")
				break
			}
		}
	}

	// Parse spec steps for structure (dependsOn, knight, domain)
	specSteps := getSlice(spec, "steps")
	specStepMap := map[string]map[string]interface{}{}
	for _, s := range specSteps {
		if sm, ok := s.(map[string]interface{}); ok {
			specStepMap[getStr(sm, "name")] = sm
		}
	}

	// Parse status steps (CRD field is "stepStatuses")
	statusSteps := getSlice(status, "stepStatuses")
	for _, s := range statusSteps {
		sm, ok := s.(map[string]interface{})
		if !ok {
			continue
		}
		stepName := getStr(sm, "name")
		step := StepSummary{
			Name:       stepName,
			Phase:      getStr(sm, "phase"),
			RetryCount: getInt(sm, "retries"),
		}

		if t := getStr(sm, "startedAt"); t != "" {
			step.StartTime = &t
		}
		if t := getStr(sm, "completedAt"); t != "" {
			step.CompletionTime = &t
		}
		if r := getStr(sm, "output"); r != "" {
			// Truncate output for list view
			if len(r) > 500 {
				truncated := r[:500] + "..."
				step.Result = &truncated
			} else {
				step.Result = &r
			}
		}

		// Merge spec info
		if ss, exists := specStepMap[stepName]; exists {
			step.Knight = getRefName(ss, "knightRef")
			if d := getStr(ss, "domain"); d != "" {
				step.Domain = d
			} else if step.Knight != "" {
				step.Domain = knights[step.Knight].Domain
			}
			if deps := getSlice(ss, "dependsOn"); deps != nil {
				for _, d := range deps {
					if ds, ok := d.(string); ok {
						step.DependsOn = append(step.DependsOn, ds)
					}
				}
			}
			step.ContinueOnFailure = getBool(ss, "continueOnFailure")
			step.OutputPath = getStr(ss, "outputPath")
			step.MaxRetries = getInt(getNestedMap(ss, "retry"), "maxAttempts")
		}
		applyStepSpecExtras(&step, specStepMap[stepName])
		applyStepStatusExtras(&step, sm, specStepMap[stepName])
		applyStepCost(&step, sm, knights)

		chain.Steps = append(chain.Steps, step)
	}

	// If no status steps yet, populate from spec
	if len(chain.Steps) == 0 {
		for _, s := range specSteps {
			sm, ok := s.(map[string]interface{})
			if !ok {
				continue
			}
			knightName := getRefName(sm, "knightRef")
			domain := getStr(sm, "domain")
			if domain == "" && knightName != "" {
				domain = knights[knightName].Domain
			}
			step := StepSummary{
				Name:              getStr(sm, "name"),
				Knight:            knightName,
				Domain:            domain,
				Phase:             "Pending",
				ContinueOnFailure: getBool(sm, "continueOnFailure"),
				OutputPath:        getStr(sm, "outputPath"),
				MaxRetries:        getInt(getNestedMap(sm, "retry"), "maxAttempts"),
			}
			applyStepSpecExtras(&step, sm)
			if deps := getSlice(sm, "dependsOn"); deps != nil {
				for _, d := range deps {
					if ds, ok := d.(string); ok {
						step.DependsOn = append(step.DependsOn, ds)
					}
				}
			}
			chain.Steps = append(chain.Steps, step)
		}
	}

	applyChainCost(&chain, status)

	return chain
}

