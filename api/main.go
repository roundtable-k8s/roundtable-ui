func knightHandler(namespace string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		vars := mux.Vars(r)
		name := vars["knight"]

		if !validK8sName.MatchString(name) {
			jsonError(w, "Invalid knight name", http.StatusBadRequest)
			return
		}

		if dynClient == nil {
			jsonError(w, "Kubernetes not available", http.StatusServiceUnavailable)
			return
		}

		// Fetch Knight CR first — it is the authoritative source
		kctx, kcancel := k8sCtx(r)
		defer kcancel()
		crObj, err := dynClient.Resource(knightGVR).Namespace(namespace).Get(kctx, name, metav1.GetOptions{})
		if err != nil {
			writeGetError(w, r, err, "Knight", "knight", name)
			return
		}

		// Find matching pods (best-effort; knight may not have any yet).
		// Prefer the ready pod so rollouts show the new pod, matching fleetHandler.
		var pods []*corev1.Pod
		if k8sClient != nil {
			podList, podErr := k8sClient.CoreV1().Pods(namespace).List(kctx, metav1.ListOptions{
				LabelSelector: fmt.Sprintf("app.kubernetes.io/name=knight,app.kubernetes.io/instance=%s", name),
			})
			if podErr == nil {
				for i := range podList.Items {
					if _, ok := podList.Items[i].Labels["job-name"]; ok {
						continue // skip CronJob pods
					}
					if len(podList.Items[i].Spec.Containers) == 0 {
						continue
					}
					pods = append(pods, &podList.Items[i])
				}
			}
		}
		var podPtr *corev1.Pod
		for _, p := range pods {
			if podPtr == nil || (!podIsReady(podPtr) && podIsReady(p)) {
				podPtr = p
			}
		}

		setSpanTable(r.Context(), getRefName(getNestedMap(crObj.Object, "spec"), "roundTableRef"))
		scaling := buildKnightScaling(r.Context(), crObj, pods)

		// Build safe DTO (#46) from CR + pods
		detail := KnightDetail{
			KnightStatus: buildKnightStatus(crObj, podPtr, scaling),
		}
		detail.Pods = buildKnightPods(pods, listPodMetrics(kctx, namespace))
		detail.Scaling = scaling
		detail.Isolation = buildKnightIsolation(crObj, podPtr, tableDefaultsFor(kctx, namespace, knightTableName(crObj)))
		if podPtr != nil {
			pod := podPtr
			detail.Node = pod.Spec.NodeName
			detail.PodName = pod.Name
			detail.PodPhase = string(pod.Status.Phase)
			if !pod.CreationTimestamp.IsZero() {
				t := pod.CreationTimestamp.Time
				detail.StartTime = &t
			}
			for _, c := range pod.Status.ContainerStatuses {
				state := "unknown"
				if c.State.Running != nil {
					state = "running"
				} else if c.State.Waiting != nil {
					state = "waiting:" + c.State.Waiting.Reason
				} else if c.State.Terminated != nil {
					state = "terminated:" + c.State.Terminated.Reason
				}
				detail.Containers = append(detail.Containers, ContainerDetail{
					Name: c.Name, Image: c.Image, Ready: c.Ready, State: state, Started: c.Started,
				})
			}
			for _, cond := range pod.Status.Conditions {
				detail.Conditions = append(detail.Conditions, PodCondition{
					Type: string(cond.Type), Status: string(cond.Status),
				})
			}
		}

		// Extract generatedSkills from CR spec
		spec := getNestedMap(crObj.Object, "spec")
		if spec != nil {
			for _, skill := range getSlice(spec, "generatedSkills") {
				if skillMap, ok := skill.(map[string]interface{}); ok {
					detail.GeneratedSkills = append(detail.GeneratedSkills, GeneratedSkill{
						Name:    getStr(skillMap, "name"),
						Content: getStr(skillMap, "content"),
					})
				}
			}
		}

		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(detail)
	}
}

// getKnightCR fetches the Knight CR by name. The session handler uses it for
// both readiness (status.ready/phase) and NATS prefix derivation with a single
// API call.
func getKnightCR(ctx context.Context, knightName string) (*unstructured.Unstructured, error) {
	if dynClient == nil {
		return nil, fmt.Errorf("kubernetes client not available")
	}
	namespace := envOr("NAMESPACE", "roundtable")
	obj, err := dynClient.Resource(knightGVR).Namespace(namespace).Get(ctx, knightName, metav1.GetOptions{})
	if err != nil {
		return nil, fmt.Errorf("failed to get knight %s: %w", knightName, err)
	}
	return obj, nil
}

// knightIsReady reports whether the operator marked the Knight as ready to
// accept tasks (status.ready, mirrored by status.phase=Ready). The operator
// derives this from deployment/pod readiness, so it doubles as a cheap
// reachability signal for introspect requests.
func knightIsReady(obj *unstructured.Unstructured) bool {
	status := getNestedMap(obj.Object, "status")
	return getBool(status, "ready") || getStr(status, "phase") == "Ready"
}

// deriveIntrospectPrefix extracts the NATS prefix for introspection from a Knight CR.
// This allows the dashboard to support multiple tables (fleet-a, chelonian, etc.) without hardcoding.
func deriveIntrospectPrefix(obj *unstructured.Unstructured) (string, error) {
	knightName := obj.GetName()

	// Extract .spec.nats.subjects[]
	subjects, found, err := unstructured.NestedStringSlice(obj.Object, "spec", "nats", "subjects")
	if err != nil || !found || len(subjects) == 0 {
		return "", fmt.Errorf("knight %s has no nats.subjects configured", knightName)
	}

	// Derive prefix using same logic as operator (internal/knight/pod_builder.go DeriveResultsPrefix)
	for _, subj := range subjects {
		if strings.Contains(subj, ".tasks.") {
			parts := strings.SplitN(subj, ".tasks.", 2)
			if len(parts) == 2 {
				return parts[0], nil
			}
		}
	}

	// Fallback: use first segment
	for _, subj := range subjects {
		parts := strings.Split(subj, ".")
		if len(parts) > 1 {
			return parts[0], nil
		}
	}

	return "", fmt.Errorf("could not derive NATS prefix from knight %s subjects", knightName)
}

// validTraceID is a W3C trace ID: 32 hex characters.
var validTraceID = regexp.MustCompile(`^[0-9a-fA-F]{32}$`)

// traceTemplate returns the trace viewer URL template when it is an http(s)
// URL containing {traceId}; otherwise "" (with a warning when it was set).
func traceTemplate(raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return ""
	}
	u, err := url.Parse(raw)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" || !strings.Contains(raw, "{traceId}") {
		slog.WarnContext(context.Background(), "TRACE_URL_TEMPLATE ignored: need an http(s) URL containing {traceId}")
		return ""
	}
	return raw
}

