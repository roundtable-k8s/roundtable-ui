// podIsReady reports whether the pod's first container is ready.
func podIsReady(pod *corev1.Pod) bool {
	return len(pod.Status.ContainerStatuses) > 0 && pod.Status.ContainerStatuses[0].Ready
}

func buildKnightStatus(cr *unstructured.Unstructured, pod *corev1.Pod, scaling *KnightScaling) KnightStatus {
	spec := getNestedMap(cr.Object, "spec")
	status := getNestedMap(cr.Object, "status")

	// Pod-derived fields (best-effort — pod may not exist yet)
	podStatus := "offline"
	var restarts int32
	var ready bool
	var image string
	var labels map[string]string
	age := time.Since(cr.GetCreationTimestamp().Time).Round(time.Second).String()

	if pod != nil {
		if pod.Labels != nil {
			labels = pod.Labels
		}
		age = time.Since(pod.CreationTimestamp.Time).Round(time.Second).String()
		if len(pod.Spec.Containers) > 0 {
			image = pod.Spec.Containers[0].Image
		}
		if len(pod.Status.ContainerStatuses) > 0 {
			cs := pod.Status.ContainerStatuses[0]
			restarts = cs.RestartCount
			ready = cs.Ready
			if ready {
				podStatus = "online"
			} else if pod.Status.Phase == "Running" {
				podStatus = "starting"
			}
		}
	}

	// An autoscaled knight parked at zero replicas is idle, not broken
	// (#166) — report it distinctly from a crashed knight (#182).
	if pod == nil && scaledToZero(scaling) {
		podStatus = "scaled-to-zero"
	}

	// Parse skills list from spec.skills
	var skillsList []string
	for _, s := range getSlice(spec, "skills") {
		if sStr, ok := s.(string); ok {
			skillsList = append(skillsList, sStr)
		}
	}

	natsPrefix, _ := deriveIntrospectPrefix(cr)

	return KnightStatus{
		NATSPrefix:         natsPrefix,
		Table:              tableOrNone(knightTableName(cr)),
		Name:               cr.GetName(),
		Domain:             getStr(spec, "domain"),
		Status:             podStatus,
		Ready:              ready,
		Restarts:           restarts,
		Age:                age,
		Image:              image,
		Labels:             labels,
		Phase:              getStr(status, "phase"),
		Model:              getStr(spec, "model"),
		SkillsList:         skillsList,
		Runtime:            getStr(spec, "runtime"),
		Suspend:            getBool(spec, "suspend"),
		TasksCompleted:     int64(getInt(status, "tasksCompleted")),
		TasksFailed:        int64(getInt(status, "tasksFailed")),
		TotalCost:          getStr(status, "totalCost"),
		Concurrency:        int32(getInt(spec, "concurrency")),
		TaskTimeoutSeconds: int32(getInt(spec, "taskTimeoutSeconds")),
	}
}

func fleetHandler(namespace string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if dynClient == nil {
			jsonError(w, "Kubernetes not available", http.StatusServiceUnavailable)
			return
		}

		crList, err := dynClient.Resource(knightGVR).Namespace(namespace).List(r.Context(), metav1.ListOptions{})
		if err != nil {
			slog.Error("K8s knight CR list error", "error", err)
			jsonError(w, "Failed to list fleet", http.StatusInternalServerError)
			return
		}

		// One pod list and one metrics list per request cycle, grouped by
		// knight instance name — never per knight (#182).
		podsByName := knightPodsByName(r.Context(), namespace)
		metrics := listPodMetrics(r.Context(), namespace)
		tableDefaults := tableDefaultsByName(r.Context(), namespace)
		filter := tableFilter(r)

		knights := make([]KnightStatus, 0, len(crList.Items))
		for i := range crList.Items {
			cr := &crList.Items[i]
			if !tableMatches(filter, knightTableName(cr)) {
				continue
			}
			pods := podsByName[cr.GetName()]
			// Preferred pod for the legacy single-pod fields: a ready one
			// first, so rollouts show the new pod.
			var podPtr *corev1.Pod
			for _, p := range pods {
				if podPtr == nil || (!podIsReady(podPtr) && podIsReady(p)) {
					podPtr = p
				}
			}
			scaling := buildKnightScaling(r.Context(), cr, pods)
			ks := buildKnightStatus(cr, podPtr, scaling)
			ks.Pods = buildKnightPods(pods, metrics)
			ks.Scaling = scaling
			ks.Isolation = buildKnightIsolation(cr, podPtr, tableDefaults[knightTableName(cr)])
			knights = append(knights, ks)
		}

		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(knights)
	}
}

