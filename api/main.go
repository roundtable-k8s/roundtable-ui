// keyEqual compares API keys in constant time. Hashing first makes the
// comparison independent of the input length.
func keyEqual(got, want string) bool {
	g, w := sha256.Sum256([]byte(got)), sha256.Sum256([]byte(want))
	return subtle.ConstantTimeCompare(g[:], w[:]) == 1
}

// authMiddleware checks the DASHBOARD_API_KEY env var for API-key based auth (#68, #65)
func authMiddleware(next http.Handler) http.Handler {
	apiKey := os.Getenv("DASHBOARD_API_KEY")
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		// If no API key is configured, auth is disabled (local dev)
		if apiKey == "" {
			next.ServeHTTP(w, r)
			return
		}

		// Skip auth for health endpoint and static files
		if r.URL.Path == "/api/health" || !strings.HasPrefix(r.URL.Path, "/api/") {
			next.ServeHTTP(w, r)
			return
		}

		// Auth endpoint: POST /api/auth/login validates the key and returns success
		if r.URL.Path == "/api/auth/login" && r.Method == "POST" {
			var body struct {
				ApiKey string `json:"apiKey"`
			}
			if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4096)).Decode(&body); err != nil {
				jsonError(w, "Invalid request", http.StatusBadRequest)
				return
			}
			if !keyEqual(body.ApiKey, apiKey) {
				jsonError(w, "Invalid API key", http.StatusUnauthorized)
				return
			}
			w.Header().Set("Content-Type", "application/json")
			json.NewEncoder(w).Encode(map[string]interface{}{
				"authenticated": true,
				"message":       "Welcome to the Round Table",
			})
			return
		}

		// Check Authorization header
		auth := r.Header.Get("Authorization")
		if auth == "" {
			// Query param is accepted for the WebSocket upgrade only: keys in
			// URLs end up in proxy logs and browser history.
			if r.URL.Path != "/api/ws" {
				// fall through to 401
			} else if qKey := r.URL.Query().Get("api_key"); qKey != "" {
				auth = "Bearer " + qKey
			}
		}

		if !strings.HasPrefix(auth, "Bearer ") || !keyEqual(strings.TrimPrefix(auth, "Bearer "), apiKey) {
			jsonError(w, "Unauthorized", http.StatusUnauthorized)
			return
		}

		next.ServeHTTP(w, r)
	})
}

// rateLimiterT is a simple fixed-window rate limiter (#12): the token bucket
// refills in full every interval. Note it is global — shared by all clients.
type rateLimiterT struct {
	mu       sync.Mutex
	tokens   int
	max      int
	interval time.Duration
	last     time.Time
}

func newRateLimiter(max int, interval time.Duration) *rateLimiterT {
	return &rateLimiterT{tokens: max, max: max, interval: interval, last: time.Now()}
}

func (rl *rateLimiterT) allow() bool {
	rl.mu.Lock()
	defer rl.mu.Unlock()
	now := time.Now()
	elapsed := now.Sub(rl.last)
	if elapsed >= rl.interval {
		rl.tokens = rl.max
		rl.last = now
	}
	if rl.tokens <= 0 {
		return false
	}
	rl.tokens--
	return true
}

func (rl *rateLimiterT) middleware(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		// Probes and scrapes must never be throttled by page traffic
		if r.URL.Path == "/api/health" || r.URL.Path == "/metrics" {
			next.ServeHTTP(w, r)
			return
		}
		if !rl.allow() {
			jsonError(w, "Rate limit exceeded", http.StatusTooManyRequests)
			return
		}
		next.ServeHTTP(w, r)
	})
}

