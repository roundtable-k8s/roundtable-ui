func parseRoundTableResource(obj map[string]interface{}) RoundTableSummary {
	spec := getNestedMap(obj, "spec")
	status := getNestedMap(obj, "status")
	metadata := getNestedMap(obj, "metadata")

	rt := RoundTableSummary{
		Name:         getStr(metadata, "name"),
		Namespace:    getStr(metadata, "namespace"),
		Phase:        getStr(status, "phase"),
		KnightsReady: getInt(status, "knightsReady"),
		KnightsTotal: getInt(status, "knightsTotal"),
		TotalCost:    getStr(status, "totalCost"),
		Description:  getStr(spec, "description"),
		Suspend:      getBool(spec, "suspend"),
		Ephemeral:    getBool(spec, "ephemeral"),

		PlannerKnight:       getStr(status, "plannerKnight"),
		KnightsScaledToZero: getInt(status, "knightsScaledToZero"),
		KnightsSuspended:    getInt(status, "knightsSuspended"),
		KnightsNotReady:     getInt(status, "knightsNotReady"),
	}
	// The planner is on unless spec.planner.enabled is false; ephemeral tables have none.
	rt.PlannerEnabled = !rt.Ephemeral
	if planner := getNestedMap(spec, "planner"); planner != nil {
		if enabled, ok := planner["enabled"].(bool); ok && !enabled {
			rt.PlannerEnabled = false
		}
	}

	// Parse totalTasksCompleted (int64)
	if status != nil {
		if v, ok := status["totalTasksCompleted"]; ok {
			switch n := v.(type) {
			case float64:
				rt.TotalTasksCompleted = int64(n)
			case int64:
				rt.TotalTasksCompleted = n
			}
		}
		rt.ActiveMissions = getInt(status, "activeMissions")
	}

	// Parse NATS config
	if nats := getNestedMap(spec, "nats"); nats != nil {
		rt.NATSPrefix = getStr(nats, "subjectPrefix")
	}

	// Parse policies
	if policies := getNestedMap(spec, "policies"); policies != nil {
		rt.CostBudgetUSD = getStr(policies, "costBudgetUSD")
		rt.Policies = &PoliciesDTO{
			CostBudgetUSD:          getStr(policies, "costBudgetUSD"),
			MaxConcurrentPlanTasks: getInt(policies, "maxConcurrentPlanTasks"),
			MaxMissions:            getInt(policies, "maxMissions"),
		}
	}

	return rt
}

